def all_bytes(s):
    return b"".join(s["clicks"]) + s["blip"] + s["beep"]


def run(*args):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        status = st.main([str(a) for a in args])
    return status, err.getvalue()


def committed_arrays():
    """name -> bytes of each array in the committed C file."""
    with open(TABLE_C, "r", encoding="utf-8") as f:
        text = f.read()
    arrays = {}
    for m in re.finditer(r"const uint8_t (\w+)\[[^=]*= \{(.*?)\n\};", text, re.S):
        arrays[m.group(1)] = bytes(int(h, 16) for h in re.findall(r"0x([0-9a-f]{2})", m.group(2)))
    return arrays


def dft_power(x, hz):
    """Power of the samples x, centred, at the frequency hz."""
    re_, im = 0.0, 0.0
    w = 2.0 * math.pi * hz / RATE
    for i, v in enumerate(x):
        re_ += (v - 128) * math.cos(w * i)
        im -= (v - 128) * math.sin(w * i)
    return re_ * re_ + im * im


def peak_hz(x, guess, spread=0.03, step=0.001):
    """The frequency near guess where x has the most power."""
    best, best_p = guess, -1.0
    k = -spread
    while k <= spread + 1e-12:
        hz = guess * (1.0 + k)
        p = dft_power(x, hz)
        if p > best_p:
            best, best_p = hz, p
        k += step
    return best


def zero_crossings_hz(x):
    """Pitch from the rising crossings of 128, first to last."""
    ups = [i for i in range(1, len(x)) if x[i - 1] < 128 <= x[i]]
    return (len(ups) - 1) * RATE / (ups[-1] - ups[0])


