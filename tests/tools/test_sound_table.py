"""Tests of tools/sound_table.py and the committed kernel/sound_table.c.

Standard library only: `make test-host` runs them with unittest. The
pitch and band checks use a small DFT written here with math.sin and
math.cos, which need not match the tool bit for bit.
"""

import contextlib
import copy
import hashlib
import importlib.util
import io
import json
import math
import os
import re
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TOOL = os.path.join(ROOT, "tools", "sound_table.py")
PARAMS = os.path.join(ROOT, "kernel", "sound_params.json")
TABLE_C = os.path.join(ROOT, "kernel", "sound_table.c")
TABLE_H = os.path.join(ROOT, "kernel", "sound_table.h")

_spec = importlib.util.spec_from_file_location("sound_table", TOOL)
st = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(st)

# SHA-256 of every click, then the blip, then the note, as the tool makes them.
RECORDED_SHA256 = "8dfe3744e0ef8e5832fe2dff8dcbc6f2f5cabc0a5059f522ee831dd500ce59f9"


def load_params():
    with open(PARAMS, "r", encoding="utf-8") as f:
        return json.load(f)


P = load_params()
RATE = P["rate_hz"]
S = st.build(P)


def all_bytes(s):
    return b"".join(s["clicks"]) + s["blip"] + s["note"]


def run(*args):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        status = st.main([str(a) for a in args])
    return status, err.getvalue()


def committed_arrays():
    """name -> bytes of each array in the committed C file."""
    with open(TABLE_C, "r", encoding="utf-8") as f:
        text = f.read()
    arrays = {}
    for m in re.finditer(r"const uint8_t (\w+)\[[^=]*= \{(.*?)\n\};", text, re.S):
        arrays[m.group(1)] = bytes(int(h, 16) for h in re.findall(r"0x([0-9a-f]{2})", m.group(2)))
    return arrays


def dft_power(x, hz):
    """Power of the samples x, centred, at the frequency hz."""
    re_, im = 0.0, 0.0
    w = 2.0 * math.pi * hz / RATE
    for i, v in enumerate(x):
        re_ += (v - 128) * math.cos(w * i)
        im -= (v - 128) * math.sin(w * i)
    return re_ * re_ + im * im


def peak_hz(x, guess, spread=0.03, step=0.001):
    """The frequency near guess where x has the most power."""
    best, best_p = guess, -1.0
    k = -spread
    while k <= spread + 1e-12:
        hz = guess * (1.0 + k)
        p = dft_power(x, hz)
        if p > best_p:
            best, best_p = hz, p
        k += step
    return best


def curve_hz(t):
    nt = P["note"]
    start, f0 = 0.0, nt["start_hz"]
    for seg in nt["segments"]:
        dur = seg["duration_ms"] / 1000.0
        if t < start + dur:
            return f0 * (seg["end_hz"] / f0) ** ((t - start) / dur)
        start += dur
        f0 = seg["end_hz"]
    return f0


def rule_steps(hz):
    nt = P["note"]
    db = 0.0
    if hz > nt["flat_to_hz"]:
        db += nt["first_slope_db_per_octave"] * math.log2(min(hz, nt["knee_hz"]) / nt["flat_to_hz"])
    if hz > nt["knee_hz"]:
        db += nt["second_slope_db_per_octave"] * math.log2(hz / nt["knee_hz"])
    return nt["top_steps"] * 10 ** (db / 20)


class Determinism(unittest.TestCase):
    def test_recorded_hash(self):
        self.assertEqual(hashlib.sha256(all_bytes(S)).hexdigest(), RECORDED_SHA256)

    def test_two_runs_equal(self):
        self.assertEqual(all_bytes(st.build(load_params())), all_bytes(S))

    def test_exact_maths(self):
        self.assertAlmostEqual(st.exp(1.0), math.e, places=13)
        self.assertAlmostEqual(st.ln(10.0), math.log(10.0), places=13)
        for i in range(100):
            self.assertLess(abs(st.sine_cycle(i / 100) - math.sin(2 * math.pi * i / 100)), 0.002)


class Check(unittest.TestCase):
    def test_committed_files_are_current(self):
        self.assertEqual(run("--check"), (0, ""))

    def test_changed_parameter_fails(self):
        p = load_params()
        p["click"]["seed"] += 1
        with tempfile.TemporaryDirectory() as d:
            path = os.path.join(d, "params.json")
            with open(path, "w", encoding="utf-8") as f:
                json.dump(p, f)
            status, err = run("--params", path, "--check")
        self.assertEqual(status, 1)
        self.assertIn("sound_table.c is stale", err)

    def test_missing_output_fails(self):
        with tempfile.TemporaryDirectory() as d:
            status, _ = run("--check", "--out-c", os.path.join(d, "x.c"), "--out-h", TABLE_H)
        self.assertEqual(status, 1)

    def test_header_line(self):
        for path in (TABLE_C, TABLE_H):
            with open(path, "r", encoding="utf-8") as f:
                self.assertTrue(f.readline().startswith("/* Generated by tools/sound_table.py"))

    def test_wav_and_dump(self):
        with tempfile.TemporaryDirectory() as d:
            self.assertEqual(run("--wav", d, "--dump", d)[0], 0)
            with open(os.path.join(d, "note.u8"), "rb") as f:
                self.assertEqual(f.read(), S["note"])
            import wave
            with wave.open(os.path.join(d, "blip.wav"), "rb") as w:
                self.assertEqual((w.getsampwidth(), w.getframerate()), (1, RATE))
                self.assertEqual(w.readframes(w.getnframes()), S["blip"])


class Ceiling(unittest.TestCase):
    def refused(self, p):
        with tempfile.TemporaryDirectory() as d:
            path = os.path.join(d, "params.json")
            with open(path, "w", encoding="utf-8") as f:
                json.dump(p, f)
            out = os.path.join(d, "out")
            status, err = run("--params", path, "--out-c", out + ".c", "--out-h", out + ".h")
            self.assertFalse(os.path.exists(out + ".c"))
        self.assertEqual(status, 2)
        self.assertIn("ceiling_steps", err)

    def test_loud_click_refused(self):
        p = copy.deepcopy(P)
        p["click"]["peak_steps"] = 13
        self.refused(p)

    def test_raised_ceiling_still_checked(self):
        p = copy.deepcopy(P)
        p["click"]["ceiling_steps"] = 4
        self.refused(p)

    def test_committed_clicks_under_ceiling(self):
        a = committed_arrays()
        c = P["click"]
        self.assertEqual(len(a["sound_click"]), c["count"] * c["samples"])
        top = max(abs(b - 128) for b in a["sound_click"])
        self.assertLessEqual(top, 12)
        self.assertEqual(top, c["peak_steps"])


class Sizes(unittest.TestCase):
    def test_committed_sizes(self):
        a = committed_arrays()
        self.assertEqual(len(a["sound_click"]), 12 * 464)
        self.assertEqual(len(a["sound_blip"]), 353)
        self.assertEqual(len(a["sound_note"]), len(S["note"]))
        # The note ends where the pitch reaches device_top_hz, 2.971 s.
        self.assertEqual(len(S["note"]), 65516)

    def test_header_matches(self):
        with open(TABLE_H, "r", encoding="utf-8") as f:
            h = f.read()
        self.assertIn("#define SOUND_NOTE_LEN      %du" % len(S["note"]), h)
        self.assertIn("#define SOUND_RATE_HZ       22050u", h)


class Click(unittest.TestCase):
    def test_levels(self):
        c = P["click"]
        for k, data in enumerate(S["clicks"]):
            want = st.round_half_away(c["peak_steps"] * c["strength_percent"][k] / 100.0)
            self.assertEqual(max(abs(b - 128) for b in data), want)
            self.assertLess(abs(sum(data) / len(data) - 128), 1.0)

    def test_band(self):
        n = P["click"]["samples"]
        bins = [0.0] * (n // 2)
        for data in S["clicks"]:
            for k in range(1, n // 2):
                bins[k] += dft_power(data, k * RATE / n)
        bands = {}
        for k in range(1, n // 2):
            hz = k * RATE / n
            b = int(hz // 250) * 250
            bands[b] = bands.get(b, 0.0) + bins[k]
        top = max(bands.values())

        def db(b):
            return 10 * math.log10(bands[b] / top)
        self.assertGreater(db(2500), -3.0)
        for b in bands:
            if b < 1500 or b >= 6500:
                self.assertLess(db(b), -15.0, "band %d Hz" % b)


class Note(unittest.TestCase):
    def window(self, t, ms=50):
        n = int(ms * RATE / 1000)
        i = int(t * RATE) - n // 2
        return S["note"][i:i + n]

    def test_pitch(self):
        # 20 ms windows: near the top the pitch climbs 5 percent in 50 ms
        # while the level falls, which pulls a 50 ms peak low.
        for t in (0.1, 0.5, 1.2, 2.0, 2.5, 2.7, 2.85, 2.9):
            want = curve_hz(t)
            got = peak_hz(self.window(t, 20), want)
            self.assertLess(abs(got / want - 1.0), 0.01, "at %.2f s" % t)

    def test_level_follows_rule_and_falls(self):
        last = None
        t = 0.2
        end = len(S["note"]) / RATE - 0.1
        while t < end:
            w = self.window(t)
            hz = curve_hz(t)
            peak = max(abs(b - 128) for b in w)
            self.assertLessEqual(abs(peak - rule_steps(hz)), 1.0, "at %.2f s" % t)
            if hz > P["note"]["flat_to_hz"] and last is not None:
                self.assertLessEqual(peak, last, "rises at %.2f s" % t)
            if hz > P["note"]["flat_to_hz"]:
                last = peak
            t += 0.05

    def test_fades(self):
        note = S["note"]
        self.assertEqual(note[0], 128)
        self.assertEqual(note[-1], 128)
        early = max(abs(b - 128) for b in note[:int(0.03 * RATE)])
        self.assertLessEqual(early, 2)


class Blip(unittest.TestCase):
    def test_two_pitches(self):
        start = 0
        for note in P["blip"]["notes"]:
            part = S["blip"][start:start + note["samples"]]
            got = peak_hz(part, note["hz"], spread=0.1)
            self.assertLess(abs(got / note["hz"] - 1.0), 0.01)
            self.assertEqual(max(abs(b - 128) for b in part), note["peak_steps"])
            start += note["samples"]
        self.assertEqual(S["blip"][0], 128)
        self.assertEqual(S["blip"][-1], 128)


if __name__ == "__main__":
    unittest.main()
