        self.assertLessEqual(max(abs(v - 128) for v in b[:94]), 6)
        self.assertLessEqual(max(abs(v - 128) for v in b[-94:]), 6)
        mid = max(abs(v - 128) for v in b[150:225])
        self.assertTrue(10 <= mid <= 15, mid)



